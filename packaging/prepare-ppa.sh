#!/usr/bin/env bash
# Vendor crates and point Cargo at vendor/ for an offline Launchpad build.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

if [[ ! -f Cargo.lock ]]; then
  echo "Cargo.lock is missing. Run: cargo generate-lockfile" >&2
  exit 1
fi

if [[ ! -f Cargo.toml ]]; then
  echo "run this from the deppo-linux repository" >&2
  exit 1
fi

echo "Vendoring crates into ./vendor (this can take a minute)..."
cargo vendor --locked vendor >/tmp/deppo-vendor-config.$$
mkdir -p .cargo
{
  echo "# Generated by packaging/prepare-ppa.sh — do not edit."
  cat /tmp/deppo-vendor-config.$$
} >.cargo/config.toml
rm -f /tmp/deppo-vendor-config.$$

if [[ ! -d vendor ]] || [[ ! -f .cargo/config.toml ]]; then
  echo "vendoring failed" >&2
  exit 1
fi

if ! grep -q 'vendored-sources\|replace-with' .cargo/config.toml; then
  echo "unexpected vendor config; check cargo vendor output" >&2
  exit 1
fi

echo "Checking offline build wiring..."
CARGO_HOME="${root}/debian/cargo_home" cargo fetch --locked --offline 2>/dev/null || true

echo "Ready."
echo "  vendor/ and .cargo/config.toml are in place (gitignored locally;"
echo "  they must be present in the source package / recipe tree)."
echo "  Next: ./packaging/build-ppa-source.sh jammy"
